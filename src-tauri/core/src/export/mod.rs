    #[test]
    fn test_start_end_gcode_included() {
        // کد start/end پروفایل در خروجی می‌آید (با مارکر پیش‌نمایش)
        let mut inp = base_input();
        inp.printer.start_gcode = "M104 S200\nM140 S60".into();
        inp.printer.end_gcode = "M104 S0".into();
        let out = compute(&inp);
        let g = serialize_gcode(&inp, &out);
        assert!(g.contains("start gcode (user profile)"));
        assert!(g.contains("M104 S200"));
        assert!(g.contains("end gcode (user profile)"));
        // کد end پروفایل قبل از پایان استاندارد می‌آید
        let pos_end_marker = g.find("end gcode").unwrap();
        let pos_m84 = g.find("M84").unwrap();
        assert!(pos_end_marker < pos_m84);
    }
