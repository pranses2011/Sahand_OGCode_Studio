    #[test]
    fn test_stl_readable_by_validator() {
        // الزام: «با parser مستقل یا validator بررسی شود» — خوانندهٔ مستقل STL
        let inp = base_input();
        let out = compute(&inp);
        let stl = serialize_stl(&out.mesh);
        // خوانندهٔ مستقل: تجزیهٔ دستی ساختار
        let n = u32::from_le_bytes([stl[80], stl[81], stl[82], stl[83]]) as usize;
        let mut valid_normals = true;
        let mut has_volume = false;
        for t in 0..n.min(100) {
            let off = 84 + t * 50;
            // normal
            let read_f32 = |o: usize| {
                f32::from_le_bytes([stl[o], stl[o + 1], stl[o + 2], stl[o + 3]])
            };
            let nx = read_f32(off);
            let ny = read_f32(off + 4);
            let nz = read_f32(off + 8);
            let len = (nx * nx + ny * ny + nz * nz).sqrt();
            if (len - 1.0).abs() > 1e-3 {
                valid_normals = false;
            }
            // رأس اول غیر NaN
            let vx = read_f32(off + 12);
            if !vx.is_finite() {
                valid_normals = false;
            }
            // attribute count = 0
            let attr = u16::from_le_bytes([stl[off + 48], stl[off + 49]]);
            if attr != 0 {
                valid_normals = false;
            }
            has_volume = true;
        }
        assert!(valid_normals, "normals یا attribute خراب‌اند");
        assert!(has_volume);
        assert!(n > 100, "mesh باید مثلث واقعی داشته باشد: {n}");
    }

