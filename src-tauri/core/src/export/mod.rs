    #[test]
    fn test_checksum_recompute_policy() {
        // بازمحاسبه: N پیوسته و checksum معتبر
        let text = "N1 G21*27\nG1 X10 Y10 F1200\nN5 G90*30\n";
        let out = recompose_with_checksum(text, ChecksumPolicy::Recompute);
        // همهٔ خطوط فرمان N و *cs دارند
        for line in out.lines() {
            if line.starts_with('N') {
                let lexed = lex_line(line, 0);
                assert!(lexed.n_word.is_some());
                assert_eq!(lexed.checksum_valid, Some(true), "خط {line}");
            }
        }
        // Nها از ۱ پیوسته‌اند
        let ns: Vec<u32> = out
            .lines()
            .filter_map(|l| {
                let lexed = lex_line(l, 0);
                lexed.n_word
            })
            .collect();
        assert_eq!(ns, vec![1, 2, 3]);
    }

