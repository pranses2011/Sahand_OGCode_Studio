/// نتیجهٔ اعتبارسنجی پیش از Save As — نمایش در «خلاصهٔ اعتبارسنجی»
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct SaveValidation {
    /// تعداد خطوط با syntax نامعتبر
    pub syntax_errors: usize,
    /// تعداد فرمان‌های نامعلوم
    pub unknown_commands: usize,
    /// تعداد هشدارهای checksum نامعتبر
    pub checksum_warnings: usize,
    /// خطوط دارای هر مشکل (ایندکس)
    pub problem_lines: Vec<usize>,
    /// پیام‌های فارسی برای نمایش
    pub messages_fa: Vec<String>,
}

pub fn serialize_gcode(input: &DesignerInput, output: &DesignerOutput) -> String {
    let printer = &input.printer;
    let mut g = String::new();

    // ---------- اعشار مختصات — نسخهٔ ۱٫۶ (کیفیت G-code) ----------
    // زبر: ۲ رقم (فایل کوچک‌تر)؛ استاندارد/ریز: ۳ (استاندارد اسلایسرها)؛
    // بسیار ریز: ۴ (برای قوس‌های نرم فریم‌ورهای مدرن)
    let q_gc = input.gcode_quality.clamp(0.25, 4.0);
    let coord_dec = if q_gc <= 0.75 {
        2
    } else if q_gc <= 2.5 {
        3
    } else {
        4
    };
    let fmt_axis = |v: f64| format!("{:.*}", coord_dec, v);

    // ---------- header کامنت (برچسب آزمایشی — الزام §7) ----------
    g.push_str("; Generated by Sahand GCode Studio (spiral designer)\n");
    g.push_str("; EXPERIMENTAL OUTPUT - review before printing\n");
    g.push_str(&format!(
        "; nozzle={}mm line_width={}mm layer_height={}mm\n",
        printer.nozzle_diameter_mm, printer.line_width_mm, printer.layer_height_mm
    ));
    g.push_str(&format!(
        "; profile='{}' ({}) volume={:.0}x{:.0}x{:.0}mm\n",
        printer.name,
        printer.status,
        printer.build_volume_mm[0],
        printer.build_volume_mm[1],
        printer.build_volume_mm[2]
    ));
    // کف — نسخهٔ ۱.۴: لایه‌های توپر + ادامهٔ vase
    if input.floor.enabled {
        g.push_str(&format!(
            "; floor: {} solid layer(s), pattern={:?}, gap={:.2}mm, hole={:.1}mm\n",
            input.floor.layers.clamp(1, 12),
            input.floor.pattern,
            input.floor.ring_gap_mm,
            input.floor.center_hole_diameter_mm
        ));
    }
    // سرعت‌ها — نمایش mm/s؛ F در فایل mm/min است (الزام G-code)
    g.push_str(&format!(
        "; speeds mm/s: wall={:.1} first_layer={:.1} floor={:.1} travel={:.1} retract={:.2}@{:.0}\n",
        printer.effective_wall_mm_min() / 60.0,
        printer.effective_first_layer_mm_min() / 60.0,
        printer.effective_floor_mm_min() / 60.0,
        printer.effective_travel_mm_min() / 60.0,
        printer.retract_mm,
        printer.retract_speed_mm_s,
    ));
    // چرخش فاز θ (درز/جهت‌گیری) — نسخهٔ ۱.۳
    g.push_str(&format!(
        "; phase_start={:.1}deg nozzle_temp={:.0}C bed_temp={:.0}C fan={:.0}%\n",
        input.phase_start_deg,
        printer.nozzle_temp_c,
        printer.bed_temp_c,
        printer.fan_percent,
    ));
    // کیفیت G-code — نسخهٔ ۱٫۶ (درخواست کاربر ۶)
    g.push_str(&format!(
        "; gcode_quality={:.2} arc_step={:.2}mm coord_decimals={}\n",
        q_gc,
        (2.0 / q_gc).clamp(0.6, 5.0),
        coord_dec
    ));

    // ---------- دماها — نسخهٔ ۱.۳ (درخواست کاربر) ----------
    // ترتیب استاندارد اسلایسرها: M140/M104 (تنظیم هدف، بدون انتظار) پیش از
    // کد start کاربر تا گرم‌شدن موازی با home/آماده‌سازی انجام شود؛ سپس
    // M190/M109 (انتظار) پیش از شروع چاپ. دمای ۰ = «فرمان صادر نکن».
    g.push_str("; --- temperatures (designer settings) ---\n");
    if printer.bed_temp_c > 0.0 {
        g.push_str(&format!("M140 S{:.0} ; set bed target\n", printer.bed_temp_c));
    }
    if printer.nozzle_temp_c > 0.0 {
        g.push_str(&format!("M104 S{:.0} ; set nozzle target\n", printer.nozzle_temp_c));
    }

    // ---------- کد start پروفایل (پیش‌نمایش‌شده در UI) ----------
    if !printer.start_gcode.trim().is_empty() {
        g.push_str("; --- start gcode (user profile) ---\n");
        g.push_str(printer.start_gcode.trim_end());
        g.push('\n');
        g.push_str("; --- end start gcode ---\n");
    }

    // ---------- حالت‌های پایه ----------
    g.push_str("G21 ; millimeters\n");
    g.push_str("G90 ; absolute XYZ\n");
    if printer.absolute_e {
        g.push_str("M82 ; absolute E\n");
    } else {
        g.push_str("M83 ; relative E\n");
    }

    // ---------- G28 خودکار — نسخهٔ ۱.۴ (استانداردسازی) ----------
    // بدون home، مختصات مطلق بی‌معنی است. اگر کد start کاربر خودش
    // G28 (یا $H گربر) ندارد، خودمان home می‌کنیم — همان رفتار
    // اسلایسرها که home را تضمین می‌کنند.
    let user_homes = printer.start_gcode.lines().any(|l| {
        let code = l.split(';').next().unwrap_or("").trim().to_uppercase();
        code.starts_with("G28") || code.contains(" G28") || code.starts_with("$H")
    });
    if !user_homes {
        g.push_str("G28 ; home all axes\n");
    }

    // ---------- انتظار دما + فن (نسخهٔ ۱.۳) ----------
    // پس از start_gcode کاربر (home/آماده‌سازی) و پیش از مسیر چاپ
    if printer.wait_for_temps {
        if printer.bed_temp_c > 0.0 {
            g.push_str(&format!("M190 S{:.0} ; wait for bed\n", printer.bed_temp_c));
        }
        if printer.nozzle_temp_c > 0.0 {
            g.push_str(&format!("M109 S{:.0} ; wait for nozzle\n", printer.nozzle_temp_c));
        }
    }
    // فن خنک‌کنندهٔ قطعه — درصد به S 0..255 (M106 مستند در knowledge)
    let fan = printer.fan_percent.clamp(0.0, 100.0);
    if fan > 0.0 {
        let s = (fan / 100.0 * 255.0).round() as u32;
        g.push_str(&format!("M106 S{s} ; part fan {:.0}%\n", fan));
    } else {
        g.push_str("M107 ; part fan off\n");
    }

    // ---------- صفر کردن E مطلق (استاندارد M82) ----------
    if printer.absolute_e {
        g.push_str("G92 E0 ; reset extruder position\n");
    }

    // ---------- بدنهٔ مسیر از IR — قواعد اسلایسرهای استاندارد ----------
    // نسخهٔ ۱.۴ (درخواست کاربر «فایل gcode خروجی رو استاندارد بکن»):
    //   * travel → G0 بدون E (قبلاً G1 با E نوشته می‌شد!)؛
    //   * F فقط هنگام «تغییر» سرعت (نه در هر خط)؛
    //   * فقط محورهای تغییرکرده در هر خط (فایل فشرده‌تر و خواناتر)؛
    //     خط نخست حرکت، هر سه محور را می‌نویسد (جای‌گیری صریح)؛
    //   * رتراکشن دور travelهای بلند کف (G1 E±… F…) — مسیر مارپیچی
    //     vase پیوسته است و رتراکشن نمی‌گیرد (زخم نمی‌اندازد)؛
    //   * ;LAYER:n و ;TYPE:FLOOR / ;TYPE:WALL-OUTER برای viewerها.
    let lh = printer.layer_height_mm.max(0.01);
    let floor_layers = input.floor.layers.clamp(1, 12) as f64;
    let floor_top = if input.floor.enabled {
        input.floor.z_start_mm.max(0.0) + floor_layers * lh
    } else {
        0.0
    };
    let retract = printer.retract_mm.max(0.0);
    let retract_f = printer.retract_speed_mm_s.max(1.0) * 60.0;

    let mut prev: Option<[f64; 3]> = output.segments.first().and_then(|s| s.start_mm);
    let mut cur_f: f64 = 0.0;
    let mut e_written = 0.0f64; // موضع فیلامنت (حالت مطلق)
    let mut retracted = false;
    let mut prev_was_extrusion = false;
    let mut first_motion = true;
    let mut layer_n: i64 = -1;
    let mut layer_z = f64::NEG_INFINITY;
    let mut cur_type = "";

    for seg in output.segments.iter() {
        let Some(end) = seg.end_mm else { continue };
        let start = seg.start_mm.or(prev).unwrap_or(end);

        // مرز لایه — فقط جابجایی‌های «پلکانی» (کف/شروع vase) لایهٔ جدیدند؛
        // پله‌های ریز مارپیچ پیوسته (dz << lh) لایه نمی‌سازند (vase است)
        if (end[2] - layer_z).abs() >= lh * 0.5 {
            layer_n += 1;
            layer_z = end[2];
            g.push_str(&format!(";LAYER:{layer_n}\n"));
        }
        // ;TYPE — کف یا دیواره (برای viewerها و تفکیک بصری)
        let want_type = if end[2] <= floor_top + lh * 0.25 {
            "FLOOR"
        } else {
            "WALL-OUTER"
        };
        if want_type != cur_type {
            cur_type = want_type;
            g.push_str(&format!(";TYPE:{cur_type}\n"));
        }

        let seg_f = seg.feedrate_mm_min.unwrap_or(0.0);
        let travel_len = {
            let d = [
                end[0] - start[0],
                end[1] - start[1],
                end[2] - start[2],
            ];
            (d[0] * d[0] + d[1] * d[1] + d[2] * d[2]).sqrt()
        };

        if seg.kind == SegmentKind::Travel {
            // رتراکشن پیش از travel بلند — فقط وقتی اکستروژنی در کار بوده
            if !retracted && retract > 0.0 && prev_was_extrusion && travel_len > 2.0 {
                if printer.absolute_e {
                    e_written -= retract;
                    g.push_str(&format!("G1 E{:.5} F{:.0} ; retract\n", e_written, retract_f));
                } else {
                    g.push_str(&format!("G1 E-{:.5} F{:.0} ; retract\n", retract, retract_f));
                }
                retracted = true;
                cur_f = retract_f;
            }
            // G0 — بدون E؛ F فقط هنگام تغییر
            let mut line = String::from("G0");
            if seg_f > 0.0 && (seg_f - cur_f).abs() > 0.5 {
                line.push_str(&format!(" F{:.0}", seg_f));
                cur_f = seg_f;
            }
            if first_motion || (end[0] - start[0]).abs() > 1e-4 {
                line.push_str(&format!(" X{}", fmt_axis(end[0])));
            }
            if first_motion || (end[1] - start[1]).abs() > 1e-4 {
                line.push_str(&format!(" Y{}", fmt_axis(end[1])));
            }
            if first_motion || (end[2] - start[2]).abs() > 1e-4 {
                line.push_str(&format!(" Z{}", fmt_axis(end[2])));
            }
            g.push_str(&line);
            g.push('\n');
            first_motion = false;
        } else {
            // آنرتراکشن پس از travel (پیش از ادامهٔ چاپ)
            if retracted {
                if printer.absolute_e {
                    e_written += retract;
                    g.push_str(&format!("G1 E{:.5} F{:.0} ; unretract\n", e_written, retract_f));
                } else {
                    g.push_str(&format!("G1 E{:.5} F{:.0} ; unretract\n", retract, retract_f));
                }
                retracted = false;
                cur_f = retract_f;
            }
            let e_delta = seg.e_delta_mm.unwrap_or(0.0);
            let mut line = String::from("G1");
            if first_motion || (end[0] - start[0]).abs() > 1e-4 {
                line.push_str(&format!(" X{}", fmt_axis(end[0])));
            }
            if first_motion || (end[1] - start[1]).abs() > 1e-4 {
                line.push_str(&format!(" Y{}", fmt_axis(end[1])));
            }
            if first_motion || (end[2] - start[2]).abs() > 1e-4 {
                line.push_str(&format!(" Z{}", fmt_axis(end[2])));
            }
            if printer.absolute_e {
                e_written += e_delta;
                line.push_str(&format!(" E{:.5}", e_written));
            } else {
                line.push_str(&format!(" E{:.5}", e_delta));
            }
            if seg_f > 0.0 && (seg_f - cur_f).abs() > 0.5 {
                line.push_str(&format!(" F{:.0}", seg_f));
                cur_f = seg_f;
            }
            g.push_str(&line);
            g.push('\n');
            first_motion = false;
        }
        prev = Some(end);
        prev_was_extrusion = seg.kind != SegmentKind::Travel;
    }

    // رتراکشن پایانی — پیش از کد end/G28 تا رشتهٔ اضافی نچکد
    if !retracted && retract > 0.0 && prev_was_extrusion {
        if printer.absolute_e {
            e_written -= retract;
            g.push_str(&format!("G1 E{:.5} F{:.0} ; retract\n", e_written, retract_f));
        } else {
            g.push_str(&format!("G1 E-{:.5} F{:.0} ; retract\n", retract, retract_f));
        }
    }

    // ---------- کد end پروفایل ----------
    if !printer.end_gcode.trim().is_empty() {
        g.push_str("; --- end gcode (user profile) ---\n");
        g.push_str(printer.end_gcode.trim_end());
        g.push('\n');
    }

    // ---------- پایان استاندارد — نسخهٔ ۱٫۶ (درخواست کاربر ۲) ----------
    // ترتیب صحیح پس از اتمام چاپ (رفع باگ «به محل اشتباهی می‌رود»):
    //   ۱) رتراکشن (بالا — پیش از کد end کاربر، رشتهٔ اضافی نمی‌چکد)؛
    //   ۲) خاموشی هیتر بستر (M140) و نازل (M104) و فن (M107) — بلافاصله؛
    //   ۳) بالارفتن ۱mm نسبی (G91 → G1 Z1 → G90) — قطعه از نازل دور می‌شود؛
    //   ۴) هوم X فقط (G28 X) — «بدون پایین آمدن»: Z همان‌جا بالا می‌ماند
    //      (قبلاً G28 کامل صادر می‌شد که Z را تا میز پایین می‌آورد و نازل
    //      داغ روی قطعه/میز گیر می‌کرد)؛
    //   ۵) خاموشی موتورها (M84).
    g.push_str("; --- shutdown sequence ---\n");
    g.push_str("M140 S0 ; bed off\n");
    g.push_str("M104 S0 ; nozzle off\n");
    g.push_str("M107 ; fan off\n");
    g.push_str("G91 ; relative mode\n");
    g.push_str("G1 Z1.0 F600 ; lift 1mm\n");
    g.push_str("G90 ; absolute mode\n");
    g.push_str("G28 X ; home X only (Z stays up)\n");
    g.push_str("M84 ; motors off\n");

    g
}

/// سریال‌سازی STL باینری استاندارد از MeshData
/// ساختار فایل: 80 بایت header + u32 تعداد مثلث + برای هر مثلث
/// 12×f32 (normal + سه رأس) + u16 attribute byte count
pub fn serialize_stl(mesh: &crate::designer::spiral::MeshData) -> Vec<u8> {
    let tri_count = mesh.triangles.len().min(u32::MAX as usize);
    // اندازهٔ کل: 80 + 4 + 50×n
    let mut buf: Vec<u8> = Vec::with_capacity(84 + 50 * tri_count);

    // header بایت‌ها (نام تولیدکننده — ASCII خالص)
    let header = b"Sahand GCode Studio spiral designer - binary STL";
    buf.extend_from_slice(&header[..]);
    // پرکردن بقیهٔ 80 بایت با صفر
    buf.resize(80, 0);

    // تعداد مثلث (little-endian u32)
    buf.extend_from_slice(&(tri_count as u32).to_le_bytes());

    for tri in mesh.triangles.iter().take(tri_count) {
        // normal واحد
        let n = mesh.triangle_normal(tri);
        for c in n {
            buf.extend_from_slice(&(c as f32).to_le_bytes());
        }
        // سه رأس
        for &idx in tri {
            let v = mesh.vertices[idx as usize];
            for c in v {
                buf.extend_from_slice(&(c as f32).to_le_bytes());
            }
        }
        // attribute byte count = 0
        buf.extend_from_slice(&0u16.to_le_bytes());
    }
    buf
}

/// اعتبارسنجی متن G-code پیش از Save As — چک‌لیست PROMPT_02 §8
/// متن کامل را با لغزندهٔ خودمان می‌خوانیم و مشکلات را فهرست می‌کنیم.
pub fn validate_save(text: &str, build_volume_mm: Option<[f64; 3]>) -> SaveValidation {
    let mut result = SaveValidation::default();
    let mut unknown_set: Vec<String> = Vec::new();

    for (i, raw_line) in text.lines().enumerate() {
        let lexed = lex_line(raw_line, i);
        // syntax نامعتبر
        if !lexed.malformed_words.is_empty() {
            result.syntax_errors += 1;
            result.problem_lines.push(i);
            result.messages_fa.push(format!(
                "خط {}: مقدار نامعتبر «{}»",
                i + 1,
                lexed.malformed_words.join("، ")
            ));
        }
        // checksum نامعتبر
        if lexed.checksum_valid == Some(false) {
            result.checksum_warnings += 1;
            result.problem_lines.push(i);
            result.messages_fa.push(format!(
                "خط {}: checksum نامعتبر (XOR مطابقت ندارد)",
                i + 1
            ));
        }
        // فرمان نامعلوم — فقط حروف فرمان (G/M/T)، نه پارامترهای X/Y/Z/E/F
        for w in &lexed.words {
            if w.number.is_some() && matches!(w.letter, 'G' | 'M' | 'T') {
                let num = w.number.unwrap() as i64 as u32;
                if knowledge::lookup(w.letter, num).is_none() {
                    let code = format!("{}{}", w.letter, num);
                    if !unknown_set.contains(&code) {
                        unknown_set.push(code.clone());
                        result.unknown_commands += 1;
                        result.messages_fa.push(format!(
                            "فرمان «{code}» در مجموعهٔ پایه شناخته نشد (وابسته به firmware)"
                        ));
                    }
                }
            }
        }
        // بازرسی bounds (فقط با پروفایل)
        if let Some(vol) = build_volume_mm {
            for w in &lexed.words {
                if w.letter == 'X' || w.letter == 'Y' {
                    if let Some(v) = w.number {
                        if v.abs() > vol[0].min(vol[1]) / 2.0 {
                            let msg = format!("خط {}: {}={} خارج از حجم ساخت", i + 1, w.letter, v);
                            if !result.messages_fa.contains(&msg) {
                                result.messages_fa.push(msg);
                            }
                        }
                    }
                }
                if w.letter == 'Z' {
                    if let Some(v) = w.number {
                        if v < -0.01 || v > vol[2] + 0.01 {
                            let msg = format!("خط {}: Z={} خارج از ارتفاع چاپ", i + 1, v);
                            if !result.messages_fa.contains(&msg) {
                                result.messages_fa.push(msg);
                            }
                        }
                    }
                }
            }
        }
    }
    result
}

/// سیاست checksum برای Save As — طبق الزام §8:
/// بازشماری N و بازمحاسبهٔ XOR با پیش‌نمایش؛ یا حذف N/checksum با هشدار.
/// حالت انتخابی: recompute (پیش‌فرض) یا strip.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ChecksumPolicy {
    /// بازمحاسبهٔ N و checksum XOR برای همهٔ خطوط فرمان‌دار
    Recompute,
    /// حذف N و *checksum با هشدار و تأیید کاربر
    Strip,
}

/// بازسازی متن با سیاست checksum
pub fn recompose_with_checksum(text: &str, policy: ChecksumPolicy) -> String {
    let mut out_lines: Vec<String> = Vec::new();
    // شمارندهٔ N جدید فقط اگر خطی N دارد از ۱ شروع و پیوسته می‌شود
    let mut n_counter: u32 = 0;
    for raw_line in text.lines() {
        let lexed = lex_line(raw_line, 0);
        let has_checksum = lexed.checksum_raw.is_some();
        let is_command = !lexed.words.is_empty()
            && lexed
                .words
                .iter()
                .any(|w| matches!(w.letter, 'G' | 'M' | 'T') && w.number.is_some());
        if !has_checksum && !is_command {
            // خط بدون فرمان دست‌نخورده
            out_lines.push(raw_line.to_string());
            continue;
        }
        // متن بدون N و بدون *cs
        let mut body = raw_line.to_string();
        // حذف checksum بخش
        if let Some(star) = body.find('*') {
            body.truncate(star);
            body = body.trim_end().to_string();
        }
        // حذف N آغازین
        if let Some(n) = lexed.n_word {
            let n_str = format!("N{n} ");
            if let Some(pos) = body.find(&n_str) {
                if pos == 0 {
                    body = body[n_str.len()..].to_string();
                }
            } else {
                // فرمت N بدون فاصله
                let n_str2 = format!("N{n}");
                if let Some(pos) = body.find(&n_str2) {
                    if pos == 0 {
                        body = body[n_str2.len()..].to_string();
                    }
                }
            }
        }
        match policy {
            ChecksumPolicy::Strip => {
                out_lines.push(body.trim().to_string());
            }
            ChecksumPolicy::Recompute => {
                if is_command {
                    n_counter += 1;
                    let with_n = format!("N{n_counter} {}", body.trim());
                    let cs = crate::gcode::lexer::compute_checksum(&with_n);
                    out_lines.push(format!("{with_n}*{}", cs as u32));
                } else {
                    out_lines.push(body.trim().to_string());
                }
            }
        }
    }
    let mut out = out_lines.join("\n");
    // پایان‌خط انتهایی اگر متن اصلی داشت
    if text.ends_with('\n') {
        out.push('\n');
    }
    out
}

