//! ============================================================================
//! gcode-core — کتابخانهٔ هستهٔ استودیوی G-code
//! ============================================================================
//! این crate «منبع واحد حقیقت» برنامه است (Docs/ARCHITECTURE.md):
//!
//!   diagnostics  : خطاها/هشدارها/عدم‌قطعیت‌ها با پیام فارسی
//!   knowledge    : دانشنامهٔ آفلاین فرمان‌های G-code (توضیح فارسی)
//!   gcode        : لغزنده + مفسر modal-state + مدیریت سند خام
//!   toolpath     : IR مشترک مسیر + قوس‌ها + لایه‌بندی
//!   designer     : موتور طراح مارپیچی (پروفایل/الگو/بافت/کف)
//!   export       : تولید G-code و STL و فایل پروژهٔ JSON
//!
//! هیچ I/O فایل/شبکه‌ای در این crate انجام نمی‌شود؛ ورودی متن/پارامتر و
//! خروجی دادهٔ سریال‌شونده است تا روی هر پلتفرمی «cargo test» شود.
//! ============================================================================

